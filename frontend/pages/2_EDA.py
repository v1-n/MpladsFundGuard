from frontend.components.explainer import render_explanation

st.set_page_config(
    page_title="EDA & Data Distributions | MPLADS FundGuard",
    page_icon="📈",
    layout="wide",
)

inject_css()

st.title("📈 Exploratory Data Analysis (EDA)")
render_disclaimer_banner()

tab1, tab2, tab3 = st.tabs([
    "📁 Dataset Catalog & Breakdown",
    "🔍 Missing Value Diagnostics",
    "📊 Empirical Feature Distributions",
])

# ----------------- TAB 1: Catalog & Breakdown -----------------
with tab1:
    try:
        eda_summary = api_client.get_eda_summary()
    except APIError as e:
        st.error(f"Error loading EDA summary: {e.message}")
        st.stop()
    except Exception as e:
        st.error(f"Failed to connect to backend: {e}")
        st.stop()

    section_header(
        title="1. Pipeline Clean Datasets Catalog",
        subtitle="Standardized datasets generated by the data ingestion pipeline",
    )
    datasets = eda_summary.get("datasets", [])
    if datasets:
        cat_df = pd.DataFrame([
            {
                "Dataset File": d["name"],
                "Row Count": f"{d['rows']:,}",
                "Columns": d["columns"],
                "Primary Columns Sample": ", ".join(d["column_names"][:5]) + ("..." if len(d["column_names"]) > 5 else ""),
            }
            for d in datasets
        ])
        styled_table(cat_df)

    section_header(
        title="2. Portfolio Classification & Categorization",
        subtitle="Distribution of works across lifecycle stages and sectoral categories",
    )
    col1, col2 = st.columns(2)

    with col1:
        lifecycle = eda_summary.get("lifecycle_breakdown", {})
        if lifecycle:
            fig_life = donut_chart(
                labels=list(lifecycle.keys()),
                values=list(lifecycle.values()),
                title="Proportion of Works by Lifecycle Stage",
                colors=["#10B981", "#8B5CF6", "#F59E0B", "#6B7280"],
            )
            st.plotly_chart(fig_life, use_container_width=True)

    with col2:
        cats = eda_summary.get("work_category_top_10", {})
        if cats:
            cat_df = pd.DataFrame({
                "Category": list(cats.keys()),
                "Works Count": list(cats.values()),
            }).sort_values(by="Works Count", ascending=True)

            fig_cat = horizontal_bar_chart(
                df=cat_df,
                x_col="Works Count",
                y_col="Category",
                title="Top 10 Work Categories by Frequency",
                text_col="Works Count",
            )
            st.plotly_chart(fig_cat, use_container_width=True)

    render_explanation(
        what="Summary of clean datasets, lifecycle stages, and sectoral category distribution in the MPLADS database.",
        why="Sectoral categorization is essential because works differ drastically in unit cost and duration (e.g. Community Halls vs Handpumps).",
        look_for="Review the proportion of in-progress vs completed works to contextualize completion lag.",
    )

# ----------------- TAB 2: Missing Values -----------------
with tab2:
    section_header(
        title="Missing Value Diagnostics Across Pipeline Tables",
        subtitle="Systematic audit of missing fields to distinguish reporting gaps from legitimate zeroes",
    )
    dataset_choice = st.selectbox(
        "Select Pipeline Table to Inspect",
        options=["master", "sanctioned", "expenditure", "completed", "mp"],
        format_func=lambda x: {
            "master": "mplads_360_master.csv (Enriched 360 View)",
            "sanctioned": "clean_works_sanctioned.csv",
            "expenditure": "clean_expenditure.csv",
            "completed": "clean_works_completed.csv",
            "mp": "clean_mp_summary.csv",
        }[x],
    )

    try:
        miss_data = api_client.get_eda_missing_values(dataset=dataset_choice)
        fields = miss_data.get("missing_fields", [])
        if fields:
            miss_df = pd.DataFrame(fields)
            display_miss = pd.DataFrame({
                "Column Name": miss_df["column"],
                "Missing Rows": miss_df["missing_count"].apply(lambda x: f"{x:,}"),
                "Missing Percentage": miss_df["missing_pct"].apply(lambda x: f"{x:.2f}%"),
                "Total Rows": miss_df["total_count"].apply(lambda x: f"{x:,}"),
            })
            styled_table(display_miss)

            fig_miss = horizontal_bar_chart(
                df=miss_df.head(12).sort_values(by="missing_pct", ascending=True),
                x_col="missing_pct",
                y_col="column",
                title=f"Highest Missingness Fields in {miss_data.get('dataset_name', '')}",
            )
            st.plotly_chart(fig_miss, use_container_width=True)
        else:
            st.success(f"No missing values found in {dataset_choice} dataset.")
    except Exception as e:
        st.error(f"Error fetching missing values: {e}")

    render_explanation(
        what="Field-by-field completeness audit across each normalized pipeline table.",
        why="Missing values in public procurement data can represent unstarted milestones (e.g. missing completion date for in-progress works) or portal data entry gaps (e.g. missing vendor names).",
        look_for="High missingness in completion photos post-mandate or vendor identifiers.",
    )

# ----------------- TAB 3: Distributions -----------------
with tab3:
    section_header(
        title="Empirical Feature Distributions",
        subtitle="Distribution histograms and robust summary statistics (Median, IQR, Mean, Min, Max)",
    )

    try:
        dist_data = api_client.get_eda_distributions()
    except Exception as e:
        st.error(f"Error fetching distribution metrics: {e}")
        st.stop()

    def render_dist_panel(hist_dict: dict, title: str, x_label: str, is_currency: bool = False):
        bins = hist_dict.get("bins", [])
        counts = hist_dict.get("counts", [])
        if not bins or not counts:
            empty_state("No distribution data available.")
            return

        bin_centers = [(bins[i] + bins[i + 1]) / 2 for i in range(len(counts))]
        bin_widths = [bins[i + 1] - bins[i] for i in range(len(counts))]

        fig = go.Figure(
            data=[
                go.Bar(
                    x=bin_centers,
                    y=counts,
                    width=bin_widths,
                    marker=dict(color="#F97316", line=dict(color="#111827", width=1)),
                )
            ]
        )
        fig.update_layout(
            title=title,
            xaxis_title=x_label,
            yaxis_title="Count of Works",
            margin=dict(l=20, r=20, t=35, b=20),
        )
        apply_dark_theme(fig)
        st.plotly_chart(fig, use_container_width=True)

        # Statistics summary table
        p25 = hist_dict.get("p25")
        p75 = hist_dict.get("p75")
        iqr_val = hist_dict.get("iqr")
        med = hist_dict.get("median_val", 0)
        mean_val = hist_dict.get("mean_val", 0)
        min_v = hist_dict.get("min_val", 0)
        max_v = hist_dict.get("max_val", 0)

        fmt_fn = lakh_crore if is_currency else (lambda x: f"{x:,.1f}" if pd.notna(x) else "—")
        stats_df = pd.DataFrame([{
            "Min": fmt_fn(min_v),
            "P25": fmt_fn(p25) if p25 is not None else "—",
            "Median (P50)": fmt_fn(med),
            "Mean": fmt_fn(mean_val),
            "P75": fmt_fn(p75) if p75 is not None else "—",
            "IQR": fmt_fn(iqr_val) if iqr_val is not None else "—",
            "Max": fmt_fn(max_v),
        }])
        styled_table(stats_df)

    dcol1, dcol2 = st.columns(2)
    with dcol1:
        render_dist_panel(
            dist_data.get("sanction_amount", {}),
            title="Sanction Amount Distribution (Clipped at P99)",
            x_label="Sanction Amount (₹)",
            is_currency=True,
        )
    with dcol2:
        render_dist_panel(
            dist_data.get("settled_expenditure", {}),
            title="Settled Expenditure Distribution (> ₹0, Clipped at P99)",
            x_label="Settled Expenditure (₹)",
            is_currency=True,
        )

    st.markdown("---")
    dcol3, dcol4 = st.columns(2)
    with dcol3:
        render_dist_panel(
            dist_data.get("execution_duration_days", {}),
            title="Execution Duration Days (0 to 1,000 Days)",
            x_label="Days from Sanction to Completion",
            is_currency=False,
        )
    with dcol4:
        render_dist_panel(
            dist_data.get("utilization_ratio", {}),
            title="Utilization Ratio Distribution (Settled / Sanctioned)",
            x_label="Ratio (0.0 to 2.0)",
            is_currency=False,
        )

    render_explanation(
        what="Histograms showing empirical frequency distributions for key project variables alongside robust location and dispersion metrics.",
        why="Public procurement distributions are severely heavy-tailed and skewed. Classical mean and standard deviation are easily distorted by mega-projects; Median and IQR provide robust baseline comparisons.",
        look_for="Compare the gap between Median and Mean to assess skewness. High IQR indicates high variance within the variable.",
    )
