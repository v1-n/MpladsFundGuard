import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent.parent
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

import pandas as pd
import streamlit as st
from frontend.api_client import api_client, APIError
from frontend.theme import inject_css
from frontend.components.disclaimer import render_disclaimer_banner
from frontend.components.formatters import lakh_crore, inr, pct
from frontend.components.metrics import metric_grid
from frontend.components.cards import section_header, empty_state
from frontend.components.dataframe import styled_table
from frontend.components.export import render_csv_download_button
from frontend.components.explainer import render_explanation

st.set_page_config(
    page_title="Anomaly Screening & Dossier | MPLADS FundGuard",
    page_icon="🛡️",
    layout="wide",
)

inject_css()

st.title("🛡️ Multi-Dimensional Anomaly Screening & Investigation")
render_disclaimer_banner()

st.info(
    "**Screening Methodology:** Anomaly scores are generated by an **Isolation Forest ensemble (10 random seeds, max_samples=1024)**, "
    "evaluating works against **stratified peer groups** (same work category and state, with fallback to national medians). "
    "Top-ranked works predominantly exhibit unusually fragmented payment structures (high installment and vendor counts) "
    "or extreme expenditures relative to peer medians. "
    "**Scores and ranks are exploratory review prioritization signals for manual audit allocation, never probabilities or assertions of wrongdoing.**"
)

# Session state for case review status
if "work_investigation_cases" not in st.session_state:
    st.session_state.work_investigation_cases = {}

# 1. Screening Search & Filters
section_header(
    title="1. Screening Search & Cohort Filters",
    subtitle="Filter multi-dimensional outliers by lifecycle cohort, geography, score, or keyword",
)

fcol1, fcol2, fcol3 = st.columns(3)
with fcol1:
    stage_choice = st.selectbox(
        "Lifecycle Cohort",
        options=["all", "Completed", "In-Progress"],
        format_func=lambda x: "All Scored Cohorts" if x == "all" else f"{x} Works Cohort",
    )
with fcol2:
    state_input = st.text_input("State Filter (Optional)", placeholder="e.g. Maharashtra, Rajasthan, Tamil Nadu")
with fcol3:
    search_query = st.text_input("Keyword Search (Work ID, MP, Constituency, Work)", placeholder="e.g. water, road, school")

scol1, scol2, scol3 = st.columns(3)
with scol1:
    min_score = st.slider("Minimum Anomaly Score Threshold", min_value=0.0, max_value=1.0, value=0.0, step=0.05)
with scol2:
    page_size = st.selectbox("Page Size", options=[25, 50, 100, 200], index=1)
with scol3:
    page_num = st.number_input("Page Number", min_value=1, value=1, step=1)

stage_param = None if stage_choice == "all" else stage_choice
state_param = state_input.strip() if state_input else None
search_param = search_query.strip() if search_query else None

try:
    anomalies, pagination = api_client.get_anomalies(
        stage=stage_param,
        state=state_param,
        min_score=float(min_score),
        search=search_param,
        sort_by="anomaly_score",
        sort_order="desc",
        page=int(page_num),
        page_size=int(page_size),
    )
    total_records = pagination.get("total_records", 0)
    total_pages = pagination.get("total_pages", 0)

    st.caption(
        f"Screening results: **{len(anomalies)}** works displayed of **{total_records:,}** matching criteria "
        f"(Page {page_num} of {max(1, total_pages)}):"
    )

    if anomalies:
        table_df = pd.DataFrame(anomalies)

        def get_priority_badge(score: float, rank: int) -> str:
            """Assigns neutral review priority tier badge."""
            if rank <= 50 or score >= 0.70:
                return "🟣 Top 1% Priority"
            elif rank <= 250 or score >= 0.55:
                return "🟣 Top 5% Priority"
            elif rank <= 500 or score >= 0.45:
                return "🟣 Top 10% Priority"
            else:
                return "⚪ Standard Priority"

        display_df = pd.DataFrame({
            "Work ID": table_df["work_id"],
            "Review Priority": [
                get_priority_badge(row.get("anomaly_score", 0), row.get("rank_in_stage", 9999))
                for _, row in table_df.iterrows()
            ],
            "Stage": table_df["stage"],
            "Rank": table_df["rank_in_stage"].apply(lambda r: f"#{r}"),
            "Anomaly Score": table_df["anomaly_score"].apply(lambda s: f"{s:.4f}"),
            "Key Contributing Factors": table_df["top_anomalous_factors"],
            "State": table_df["state"],
            "Constituency": table_df["constituency"],
            "MP Name": table_df["mp_name"],
            "Work Description": table_df["work"],
            "Sanctioned": table_df["sanction_amount"].apply(lambda x: lakh_crore(x) if pd.notna(x) else "—"),
            "Settled Exp": table_df["total_exp_settled"].apply(lambda x: lakh_crore(x) if pd.notna(x) else "—"),
            "Peer Tier": table_df["peer_tier"].fillna("—"),
            "Rule Flags": table_df["n_rule_flags"],
        })

        styled_table(display_df)

        render_csv_download_button(
            df=display_df,
            filename=f"anomaly_screening_{stage_choice}_page{page_num}.csv",
            button_label="📥 Export Screened Works Table to Sanitized CSV",
        )

        # 2. Comprehensive Work Dossier
        section_header(
            title="2. Work Dossier & Verification Detail",
            subtitle="Granular multi-dimensional indicators, payment fragmentation, and peer comparisons",
            badge="Review Dossier",
        )

        work_options = list(table_df["work_id"])
        selected_work = st.selectbox("Select Project to Inspect", options=work_options)

        if selected_work:
            try:
                detail = api_client.get_anomaly_detail(work_id=selected_work)

                st.markdown(f"#### 🔍 Project Dossier: `{detail.get('work_id')}`")

                dossier_col1, dossier_col2 = st.columns([3, 1])
                with dossier_col1:
                    st.info(f"**Work Description:** {detail.get('work_description') or detail.get('work')}")
                with dossier_col2:
                    st.link_button(
                        "🔗 Open Official MPLADS Portal",
                        "https://www.mplads.gov.in/",
                        help="Cross-reference payment bills, sanction orders, and completion photos on the portal",
                    )

                # Dossier Metric Grid
                dossier_items_1 = [
                    {
                        "label": "Anomaly Score",
                        "value": f"{detail.get('anomaly_score', 0):.4f}",
                        "subtext": "Isolation Forest ensemble score",
                        "badge": "Priority Metric",
                        "badge_variant": "top1",
                    },
                    {
                        "label": "Rank in Stage",
                        "value": f"#{detail.get('rank_in_stage', 0):,}",
                        "subtext": f"{detail.get('stage')} cohort rank",
                        "badge": "Cohort Rank",
                        "badge_variant": "neutral",
                    },
                    {
                        "label": "Sanctioned Budget",
                        "value": lakh_crore(detail.get("sanction_amount")),
                        "subtext": "Approved allocation",
                        "badge": "Sanctioned",
                        "badge_variant": "neutral",
                    },
                    {
                        "label": "Settled Expenditure",
                        "value": lakh_crore(detail.get("total_exp_settled")),
                        "subtext": "Disbursed expenditure",
                        "badge": "Disbursed",
                        "badge_variant": "pass",
                    },
                ]
                metric_grid(dossier_items_1, cols=4)

                dossier_items_2 = [
                    {
                        "label": "Payment Installments",
                        "value": str(detail.get("installments_count", 0)),
                        "subtext": f"{detail.get('settled_count', 0)} settled • {detail.get('in_progress_count', 0)} pending",
                        "badge": "Installments",
                        "badge_variant": "neutral",
                    },
                    {
                        "label": "Unique Vendors",
                        "value": str(detail.get("vendors_count", 0)),
                        "subtext": "Paid vendor entities",
                        "badge": "Vendors",
                        "badge_variant": "neutral",
                    },
                    {
                        "label": "Primary Vendor",
                        "value": str(detail.get("primary_vendor", "Unknown"))[:25],
                        "subtext": "Principal contractor/supplier",
                        "badge": "Vendor Entity",
                        "badge_variant": "neutral",
                    },
                    {
                        "label": "Peer Group Median",
                        "value": lakh_crore(detail.get("peer_median_settled")),
                        "subtext": f"Benchmark: {detail.get('peer_tier', 'Tier 1')}",
                        "badge": "Peer Baseline",
                        "badge_variant": "neutral",
                    },
                ]
                metric_grid(dossier_items_2, cols=4)

                # Reviewer Case Status Management
                section_header(
                    title="Case Tracking & Reviewer Notes",
                    subtitle="Record exploratory review status locally during this session",
                )
                case_info = st.session_state.work_investigation_cases.get(
                    selected_work, {"status": "Unreviewed", "notes": ""}
                )

                case_status_opts = [
                    "Unreviewed",
                    "Under Review",
                    "Prioritized for Field Verification",
                    "Resolved (Verified Expected Pattern)",
                    "Resolved (Data Entry Anomaly)",
                ]
                c_idx = case_status_opts.index(case_info["status"]) if case_info["status"] in case_status_opts else 0

                ccol1, ccol2 = st.columns([1, 2])
                with ccol1:
                    new_case_status = st.selectbox(
                        "Review Status",
                        options=case_status_opts,
                        index=c_idx,
                        key=f"c_stat_{selected_work}",
                    )
                with ccol2:
                    new_case_notes = st.text_input(
                        "Reviewer Case Notes",
                        value=case_info.get("notes", ""),
                        placeholder="e.g. Scope justified; multi-component school equipment package...",
                        key=f"c_notes_{selected_work}",
                    )

                if st.button("💾 Update Case Note", key=f"save_case_{selected_work}"):
                    st.session_state.work_investigation_cases[selected_work] = {
                        "status": new_case_status,
                        "notes": new_case_notes,
                    }
                    st.success(f"Case for `{selected_work}` updated to `{new_case_status}`.")
                    st.rerun()

                # Detailed breakdown tabs
                t_factors, t_timeline, t_flags, t_compare = st.tabs([
                    "🏷️ Contributing Factors & Peer Benchmark",
                    "⏱️ Timeline & Milestones",
                    "🚩 Ledger Rule Flags",
                    "⚖️ Compare with Peer Work",
                ])

                with t_factors:
                    st.markdown("**Key Multi-Dimensional Deviation Indicators:**")
                    st.info(detail.get("top_anomalous_factors") or "No dominant factor identified")

                    col_f1, col_f2 = st.columns(2)
                    with col_f1:
                        st.markdown(f"- **Peer Benchmark Tier:** `{detail.get('peer_tier', 'Tier 1')}`")
                        st.markdown(f"- **Log Relative Cost Difference vs Peer Median:** `{detail.get('paid_vs_peer_log', 0):.3f}`")
                    with col_f2:
                        u_pct = detail.get("utilization_ratio", 0) * 100 if detail.get("utilization_ratio") else 0
                        st.markdown(f"- **Utilization Ratio:** `{u_pct:.1f}%`")
                        st.markdown(f"- **Cost Variance (Settled - Sanctioned):** `{lakh_crore(detail.get('cost_variance', 0))}`")

                with t_timeline:
                    dcol1, dcol2, dcol3 = st.columns(3)
                    with dcol1:
                        st.markdown(f"**Recommended Date:** `{detail.get('recommended_date') or '—'}`")
                        st.markdown(f"**Sanction Date:** `{detail.get('sanction_date') or '—'}`")
                        st.markdown(f"**Completion Date:** `{detail.get('completion_date') or '—'}`")
                    with dcol2:
                        st.markdown(f"**Sanction Approval Lag:** `{detail.get('sanction_approval_days') or 0:.0f} days`")
                        st.markdown(f"**Execution Duration:** `{detail.get('execution_duration_days') or 0:.0f} days`")
                        st.markdown(f"**First Payment Lag:** `{detail.get('first_payment_lag_days') or 0:.0f} days`")
                    with dcol3:
                        st.markdown(f"**Settled Disbursements:** `{detail.get('settled_count', 0)}`")
                        st.markdown(f"**Pending Disbursements:** `{detail.get('in_progress_count', 0)}`")

                with t_flags:
                    flags = detail.get("rule_flags", {})
                    active_flags = {k: v for k, v in flags.items() if v == 1}
                    if active_flags:
                        st.warning(f"Active Rule Flags Triggered: {list(active_flags.keys())}")
                    else:
                        st.success("No deterministic ledger rule flags triggered for this work.")

                    st.caption(f"**Methodology Note:** {detail.get('methodology_note')}")

                with t_compare:
                    st.markdown("##### Side-by-Side Work Comparison")
                    compare_candidates = [w for w in work_options if w != selected_work]
                    if compare_candidates:
                        comp_target = st.selectbox(
                            "Select Second Work to Compare",
                            options=compare_candidates,
                            key="comp_sel",
                        )
                        try:
                            comp_detail = api_client.get_anomaly_detail(work_id=comp_target)

                            comp_table = [
                                {"Metric": "Work Description", "Selected Work": detail.get("work"), "Comparison Work": comp_detail.get("work")},
                                {"Metric": "State / Constituency", "Selected Work": f"{detail.get('state')} / {detail.get('constituency')}", "Comparison Work": f"{comp_detail.get('state')} / {comp_detail.get('constituency')}"},
                                {"Metric": "Anomaly Score", "Selected Work": f"{detail.get('anomaly_score', 0):.4f}", "Comparison Work": f"{comp_detail.get('anomaly_score', 0):.4f}"},
                                {"Metric": "Rank in Stage", "Selected Work": f"#{detail.get('rank_in_stage', 0)}", "Comparison Work": f"#{comp_detail.get('rank_in_stage', 0)}"},
                                {"Metric": "Sanctioned Amount", "Selected Work": lakh_crore(detail.get("sanction_amount")), "Comparison Work": lakh_crore(comp_detail.get("sanction_amount"))},
                                {"Metric": "Settled Expenditure", "Selected Work": lakh_crore(detail.get("total_exp_settled")), "Comparison Work": lakh_crore(comp_detail.get("total_exp_settled"))},
                                {"Metric": "Payment Installments", "Selected Work": str(detail.get("installments_count", 0)), "Comparison Work": str(comp_detail.get("installments_count", 0))},
                                {"Metric": "Unique Vendors", "Selected Work": str(detail.get("vendors_count", 0)), "Comparison Work": str(comp_detail.get("vendors_count", 0))},
                                {"Metric": "Primary Vendor", "Selected Work": detail.get("primary_vendor", "—"), "Comparison Work": comp_detail.get("primary_vendor", "—")},
                                {"Metric": "Peer Group Median", "Selected Work": lakh_crore(detail.get("peer_median_settled")), "Comparison Work": lakh_crore(comp_detail.get("peer_median_settled"))},
                            ]
                            styled_table(pd.DataFrame(comp_table))
                        except Exception as e:
                            st.error(f"Error loading comparison work: {e}")

            except Exception as e:
                st.error(f"Error fetching detail for {selected_work}: {e}")

    else:
        empty_state("No works found matching the selected filters.")

except Exception as e:
    st.error(f"Error executing anomaly screening query: {e}")

render_explanation(
    what="Multi-dimensional anomaly detection using an ensemble of Isolation Forests benchmarked against peer groups.",
    why="Identifies works that exhibit unusual combinations of cost, duration, and payment fragmentation relative to comparable projects.",
    look_for="Check whether high scores are driven by expected multi-component projects or unusual payment installment fragmentation.",
)
